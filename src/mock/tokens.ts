export const generateMockPriceHistory = (
  basePrice: number,
  days: number
): PricePoint[] => {
  const points: PricePoint[] = []
  const now = Date.now()
  const msPerDay = 86400000

  for (let i = days; i >= 0; i--) {
    const variance = (Math.random() - 0.48) * basePrice * 0.04
    const prevPrice = points.length > 0 ? points[points.length - 1]!.price : basePrice
    const price = Math.max(prevPrice + variance, basePrice * 0.5)
    points.push({
      timestamp: now - i * msPerDay,
      price: parseFloat(price.toFixed(2)),
    })
  }

  return points
}
